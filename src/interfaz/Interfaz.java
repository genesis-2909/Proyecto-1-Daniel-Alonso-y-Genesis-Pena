    private void botonCargarArchivoTXTActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_botonCargarArchivoTXTActionPerformed
    /**
     * Maneja el evento de clic en el botón de cargar archivo.
     * Despliega una advertencia sobre la pérdida de datos no guardados y,
     * tras la confirmación, abre un explorador de archivos para seleccionar
     * el documento con las interacciones proteicas.
     * @param evt El evento de acción generado al presionar el botón.
     */
        int confirmacion = javax.swing.JOptionPane.showConfirmDialog(this,
                "¿Ha guardado los datos actuales? Cargar un nuevo archivo sobrescribirá la información en memoria.",
                "Alerta de Seguridad",
                javax.swing.JOptionPane.YES_NO_OPTION,
                javax.swing.JOptionPane.WARNING_MESSAGE);

        if (confirmacion == javax.swing.JOptionPane.YES_OPTION) {
            javax.swing.JFileChooser fileChooser = new javax.swing.JFileChooser();
            fileChooser.setDialogTitle("Seleccione el archivo de interacciones (.txt o .csv)");

            int seleccion = fileChooser.showOpenDialog(this);

            if (seleccion == javax.swing.JFileChooser.APPROVE_OPTION) {
                java.io.File archivoSeleccionado = fileChooser.getSelectedFile();
                leerDatosDeArchivo(archivoSeleccionado);
            }
        }
        
    }//GEN-LAST:event_botonCargarArchivoTXTActionPerformed

