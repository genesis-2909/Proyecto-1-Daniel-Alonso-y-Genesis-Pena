    /**
     * Extrae los datos de los campos de texto, los valida y agrega una nueva 
     * interacción (arista) entre dos proteínas (vértices) en el grafo principal.
     * Muestra alertas informativas sobre el resultado de la operación.
     * * @param evt El evento de acción generado al presionar el botón de agregar.
     */    
    private void btnAgregarInteraccionActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarInteraccionActionPerformed
        /** Extraemos el texto que el usuario escribió en los campos */
        String origen = txtProteinaOrigen.getText().trim();
        String destino = txtProteinaDestino.getText().trim();
        String pesoStr = txtPeso.getText().trim();

        /** Validamos que no haya dejado ningún campo vacío */
        if (origen.isEmpty() || destino.isEmpty() || pesoStr.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "Por favor, llene todos los campos (Origen, Destino y Peso).",
                    "Campos Incompletos",
                    javax.swing.JOptionPane.WARNING_MESSAGE);
            return; 
        }

        try {
            /** Convertimos el texto del peso a un número con decimales (Double) */
            double peso = Double.parseDouble(pesoStr);

            /** Le enviamos los datos al grafo principal */
            grafoPrincipal.agregarInteraccion(origen, destino, peso);

            /** Le avisamos al usuario que la operación fue exitosa */
            javax.swing.JOptionPane.showMessageDialog(this,
                    "¡Interacción agregada exitosamente!\n" + origen + " <-> " + destino + " (Peso: " + peso + ")",
                    "Éxito",
                    javax.swing.JOptionPane.INFORMATION_MESSAGE);

            /** Limpiamos los campos de texto para la siguiente entrada */
            txtProteinaOrigen.setText("");
            txtProteinaDestino.setText("");
            txtPeso.setText("");

        } catch (NumberFormatException e) {
            /** Atajamos el error si el usuario no ingresa un número válido en el peso */
            javax.swing.JOptionPane.showMessageDialog(this,
                    "Error: El peso debe ser un número válido (ejemplo: 5.5 o 3).",
                    "Error de Formato",
                    javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnAgregarInteraccionActionPerformed

    /**
     * Extrae el nombre de la proteína del campo de texto y la elimina del grafo 
     * principal, incluyendo todas sus interacciones (aristas) asociadas.
     * Muestra alertas informativas sobre el resultado de la operación.
     * @param evt El evento de acción generado al presionar el botón de eliminar.
     */
    private void btnEliminarProteinaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarProteinaActionPerformed
        /** Se extrae y limpia el texto ingresado por el usuario */
        String proteinaAEliminar = txtProteinaEliminar.getText().trim();

        /** Se valida que el campo de texto no se encuentre vacío */
        if (proteinaAEliminar.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "Por favor, ingrese el nombre de la proteína que desea eliminar.",
                    "Campo Vacío",
                    javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }

        /** Se verifica la existencia del vértice en el grafo antes de proceder */
        if (grafoPrincipal.buscarVertice(proteinaAEliminar) != null) {
            
            /** Se ejecuta la eliminación de la proteína y sus aristas */
            grafoPrincipal.eliminarProteina(proteinaAEliminar);
            
            /** Se notifica al usuario que la operación fue exitosa */
            javax.swing.JOptionPane.showMessageDialog(this,
                    "La proteína '" + proteinaAEliminar + "' y todas sus interacciones han sido eliminadas.",
                    "Eliminación Exitosa",
                    javax.swing.JOptionPane.INFORMATION_MESSAGE);
            
            /** Se limpia el campo de texto para futuras operaciones */
            txtProteinaEliminar.setText("");
            
        } else {
            /** Se muestra un mensaje de error si la proteína no existe */
            javax.swing.JOptionPane.showMessageDialog(this,
                    "La proteína '" + proteinaAEliminar + "' no se encuentra en el sistema.",
                    "Proteína No Encontrada",
                    javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnEliminarProteinaActionPerformed

