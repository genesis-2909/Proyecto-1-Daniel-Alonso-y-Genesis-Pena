    /**
     * Lee el archivo de texto plano seleccionado y carga las interacciones proteicas
     * en el grafo principal del sistema. El formato esperado por línea es:
     * Proteina_A, Proteina_B, Costo_Interaccion.
     * * @author Daniel Alonso y Génesis Peña
     * @param archivo El archivo seleccionado por el usuario mediante el JFileChooser.
     */
    private void leerDatosDeArchivo(java.io.File archivo) {
        try {
            java.io.BufferedReader br = new java.io.BufferedReader(new java.io.FileReader(archivo));
            String linea;
            grafoPrincipal = new Grafos.Grafo(); 

            while ((linea = br.readLine()) != null) {
                if (linea.trim().isEmpty()) {
                    continue;
                }
                
                String[] partes = linea.split(",");
                if (partes.length == 3) {
                    String proteinaA = partes[0].trim();
                    String proteinaB = partes[1].trim();
                    double peso = Double.parseDouble(partes[2].trim());
                    
                    grafoPrincipal.agregarInteraccion(proteinaA, proteinaB, peso);
                }
            }
            br.close();
            javax.swing.JOptionPane.showMessageDialog(this, 
                    "¡Datos cargados exitosamente! Total de proteínas procesadas: " + grafoPrincipal.getCantidadVertices());

        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(this, 
                    "Error al leer el archivo. Verifique el formato.\nDetalle: " + e.getMessage(), 
                    "Error de Lectura", 
                    javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }
